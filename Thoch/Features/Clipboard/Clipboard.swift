import SwiftUI
import AppKit
import Combine

// MARK: - Data riwayat clipboard

struct ClipItem: Identifiable {
    enum Kind {
        case text(String)
        case image(NSImage)
    }

    let id = UUID()
    var date: Date
    let kind: Kind
}

/// Mencatat 20 teks / gambar terakhir yang di-copy.
/// Sengaja hanya disimpan di memori (hilang saat app ditutup) demi privasi.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    @Published private(set) var items: [ClipItem] = []

    private let limit = 20
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Penanda dari password manager & app lain bahwa isinya rahasia / sementara
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    private init() {}

    /// macOS tidak punya notifikasi clipboard, jadi dicek tiap 0,5 detik (sangat ringan)
    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return } // isi rahasia → lewati
        guard !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return } // copy file → urusan Tray

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(.text(text))
        } else if let image = NSImage(pasteboard: pb) {
            insert(.image(image))
        }
    }

    private func insert(_ kind: ClipItem.Kind) {
        // Teks yang sama → pindah ke atas, jangan dobel
        if case .text(let new) = kind {
            items.removeAll { if case .text(let old) = $0.kind { return old == new }; return false }
        }
        withAnimation(.snappy) {
            items.insert(ClipItem(date: Date(), kind: kind), at: 0)
            if items.count > limit { items.removeLast(items.count - limit) }
        }
    }

    /// Copy ulang item ke clipboard
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text(let text): pb.setString(text, forType: .string)
        case .image(let image): pb.writeObjects([image])
        }
        lastChange = pb.changeCount
        // Posisi tidak dipindah, supaya baris tetap di bawah kursor dan bisa menampilkan "Copied"
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            items[i].date = Date()
        }
        ToastController.shared.show(icon: "doc.on.doc.fill", text: "Copied")
    }

    func remove(_ item: ClipItem) {
        withAnimation(.snappy) { items.removeAll { $0.id == item.id } }
    }

    func clear() {
        withAnimation(.snappy) { items.removeAll() }
    }
}

// MARK: - Tab Clipboard

struct ClipboardPage: View {
    @ObservedObject private var store = ClipboardStore.shared

    var body: some View {
        GlassCard {
            VStack(alignment: .leading, spacing: 10) {
                HStack(alignment: .firstTextBaseline, spacing: 6) {
                    Text("CLIPBOARD")
                        .font(.system(size: 10, weight: .bold))
                        .foregroundStyle(Theme.primary)
                    if !store.items.isEmpty {
                        Text("\(store.items.count) recent")
                            .font(.system(size: 10, weight: .medium))
                            .opacity(0.5)
                    }
                    Spacer()
                    if !store.items.isEmpty {
                        Button("Clear") { store.clear() }
                            .buttonStyle(.plain)
                            .font(.system(size: 10, weight: .medium))
                            .opacity(0.6)
                    }
                }

                if store.items.isEmpty {
                    VStack(spacing: 6) {
                        Image(systemName: "doc.on.clipboard")
                            .font(.system(size: 20, weight: .medium))
                        Text("Nothing copied yet")
                            .font(.system(size: 12, weight: .semibold))
                        Text("Text and images you copy show up here")
                            .font(.system(size: 10))
                            .opacity(0.7)
                    }
                    .opacity(0.5)
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
                } else {
                    ScrollView(.vertical, showsIndicators: false) {
                        LazyVStack(spacing: 6) {
                            ForEach(store.items) { item in
                                ClipRow(item: item)
                            }
                        }
                    }
                }
            }
        }
    }
}

struct ClipRow: View {
    let item: ClipItem
    @State private var hovering = false
    /// Setelah diklik → "Copied", reset saat kursor keluar dari baris
    @State private var copied = false

    var body: some View {
        Button {
            ClipboardStore.shared.copy(item)
            withAnimation(.snappy(duration: 0.18)) { copied = true }
        } label: {
            HStack(spacing: 10) {
                preview
                    .frame(width: 30, height: 30)
                    .clipShape(RoundedRectangle(cornerRadius: 7, style: .continuous))

                Text(title)
                    .font(.system(size: 12, weight: .medium))
                    .lineLimit(2)
                    .multilineTextAlignment(.leading)
                    .frame(maxWidth: .infinity, alignment: .leading)

                // Saat hover: waktu diganti ikon + "Copy"
                ZStack(alignment: .trailing) {
                    Text(item.date.formatted(.relative(presentation: .named)))
                        .font(.system(size: 10))
                        .opacity(hovering ? 0 : 0.4)
                    HStack(spacing: 4) {
                        Image(systemName: copied ? "checkmark" : "doc.on.doc")
                            .font(.system(size: 10, weight: .semibold))
                            .contentTransition(.symbolEffect(.replace))
                        Text(copied ? "Copied" : "Copy")
                            .font(.system(size: 10, weight: .semibold))
                    }
                    .foregroundStyle(Theme.primary)
                    .opacity(hovering ? 1 : 0)
                    .offset(x: hovering ? 0 : 4)
                }
                .animation(.snappy(duration: 0.18), value: hovering)
            }
            .padding(8)
            .background(Color.white.opacity(hovering ? 0.12 : 0.05),
                        in: RoundedRectangle(cornerRadius: 10, style: .continuous))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .onHover { inside in
            hovering = inside
            if !inside { copied = false } // keluar dari baris → kembali ke "Copy"
        }
        .contextMenu {
            Button("Copy") { ClipboardStore.shared.copy(item) }
            Button("Delete") { ClipboardStore.shared.remove(item) }
        }
    }

    @ViewBuilder
    private var preview: some View {
        switch item.kind {
        case .text:
            ZStack {
                Color.white.opacity(0.08)
                Image(systemName: "text.alignleft")
                    .font(.system(size: 12, weight: .semibold))
                    .opacity(0.6)
            }
        case .image(let image):
            Image(nsImage: image)
                .resizable()
                .aspectRatio(contentMode: .fill)
        }
    }

    private var title: String {
        switch item.kind {
        case .text(let text):
            return text.trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ")
        case .image(let image):
            return "Image · \(Int(image.size.width))×\(Int(image.size.height))"
        }
    }
}
